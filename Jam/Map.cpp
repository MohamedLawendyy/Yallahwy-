// Initialize static members
size_t Map::WIDTH = 32;
size_t Map::HEIGHT = 16;
float Map::TILE_SIZE = 64.0f;

void Map::initializeDimensions(unsigned int screenWidth, unsigned int screenHeight)
{
    const float TARGET_TILE_SIZE = 64.0f;
    WIDTH = static_cast<size_t>(screenWidth / TARGET_TILE_SIZE);
    HEIGHT = static_cast<size_t>(screenHeight / TARGET_TILE_SIZE);

    if (WIDTH < 20)
        WIDTH = 20;
    if (HEIGHT < 12)
        HEIGHT = 12;

    TILE_SIZE = static_cast<float>(screenWidth) / static_cast<float>(WIDTH);
    HEIGHT = static_cast<size_t>(screenHeight / TILE_SIZE);

    std::cout << "Map dimensions: " << WIDTH << "x" << HEIGHT
              << " tiles, tile size: " << TILE_SIZE << "px" << std::endl;
}

Map::Map(const MapConfig &config, b2World *physicsWorld)
    : config_(config), physicsWorld_(physicsWorld)
{
    grid_.resize(HEIGHT);
    for (auto &row : grid_)
    {
        row.resize(WIDTH);
    }

    // Load from CSV generated by tilemap editor
    if (!loadFromCSV("maps/map_1.csv"))
    {
        std::cerr << "Failed to load map from CSV, creating empty map" << std::endl;
        initializeGrid();
    }

    // Create physics colliders if physics world is available
    if (physicsWorld_)
    {
        createPhysicsColliders();
    }
}

bool Map::loadFromCSV(const std::string &filename)
{
    std::ifstream file(filename);
    if (!file.is_open())
    {
        std::cerr << "Could not open map file: " << filename << std::endl;
        return false;
    }

    std::string line;
    bool readingBase = false;
    bool readingOverlay = false;
    size_t row = 0;

    clearGrid();
    clearPhysicsBodies();

    std::cout << "Loading map from " << filename << "..." << std::endl;

    while (std::getline(file, line))
    {
        // Check for layer markers
        if (line == "BASE_LAYER")
        {
            readingBase = true;
            readingOverlay = false;
            row = 0;
            continue;
        }
        else if (line == "OVERLAY_LAYER")
        {
            readingBase = false;
            readingOverlay = true;
            row = 0;
            continue;
        }

        // Skip empty lines
        if (line.empty())
            continue;

        // Parse CSV line
        if ((readingBase || readingOverlay) && row < HEIGHT)
        {
            std::stringstream ss(line);
            std::string value;
            size_t col = 0;

            while (std::getline(ss, value, ',') && col < WIDTH)
            {
                try
                {
                    int tileId = std::stoi(value);

                    if (readingBase)
                    {
                        // Map tile IDs from editor to game tile states
                        grid_[row][col].state = mapEditorIdToTileState(tileId);

                        // Store wall type for walls
                        if (grid_[row][col].state == TileState::Wall)
                        {
                            grid_[row][col].wallType = mapEditorIdToWallType(tileId);
                        }

                        // Store original tile ID for debugging
                        grid_[row][col].editorTileId = tileId;
                    }
                    else if (readingOverlay)
                    {
                        // Handle overlay data (props, decorations)
                        if (tileId != 0) // 0 means empty
                        {
                            mapOverlayToDecoration(col, row, tileId);
                        }
                    }
                }
                catch (const std::exception &e)
                {
                    std::cerr << "Error parsing tile at (" << col << "," << row << "): " << e.what() << std::endl;
                }
                col++;
            }
            row++;
        }
    }

    file.close();

    // Apply auto-tiling to fix any wall connections
    applyAutoTiling();

    // Find safe spawn point (look for Entrance tile)
    findSafeSpawnPoint();

    // Convert some floors to flammable (grass)
    std::random_device rd;
    std::mt19937 gen(rd());
    convertFloorToFlammable(gen);

    std::cout << "✓ Map loaded successfully from " << filename << std::endl;
    std::cout << "  Grid size: " << WIDTH << "x" << HEIGHT << std::endl;
    std::cout << "  Safe spawn: (" << safeSpawnPoint_.x << ", " << safeSpawnPoint_.y << ")" << std::endl;

    markFurnitureAsFlammable();

    return true;
}

TileState Map::mapEditorIdToTileState(int editorId)
{
    switch (editorId)
    {
    case EDITOR_FLOOR:
        return TileState::Floor;

    // All wall types map to Wall state
    case EDITOR_WALL_MID_TOP:
    case EDITOR_WALL_MID_BOTTOM:
    case EDITOR_CLASSWALL_TOP:
    case EDITOR_CLASSWALL_BOTTOM:
    case EDITOR_WALL_SEP_LEFT:
    case EDITOR_WALL_SEP_RIGHT:
    case EDITOR_WALL_SEP_BOTTOM:
    case EDITOR_CORNER_BR1:
    case EDITOR_CORNER_BR2:
    case EDITOR_CORNER_BL1:
    case EDITOR_CORNER_BL2:
    case EDITOR_CORNER_TL:
    case EDITOR_CORNER_TR:
        return TileState::Wall;

    case EDITOR_NONE:
    default:
        return TileState::Empty; // Changed from Floor to Empty for void areas
    }
}

