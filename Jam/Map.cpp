void Map::markFurnitureAsFlammable()
{
    std::cout << "Marking furniture tiles as flammable..." << std::endl;
    int flammableCount = 0;

    for (size_t y = 0; y < HEIGHT; ++y)
    {
        for (size_t x = 0; x < WIDTH; ++x)
        {
            Tile &tile = grid_[y][x];

            // Check if this tile has flammable furniture in overlay
            bool isFurniture = (tile.overlayTileId == 21 || // Chair
                                tile.overlayTileId == 22 || // Desk TL
                                tile.overlayTileId == 23 || // Desk TR
                                tile.overlayTileId == 24 || // Desk BL
                                tile.overlayTileId == 25 || // Desk BR
                                tile.overlayTileId == 26 || // Plant Top
                                tile.overlayTileId == 27 || // Plant Bottom
                                tile.overlayTileId == 36);  // Box

            if (isFurniture)
            {
                // Make this tile flammable
                tile.state = TileState::Flammable;
                tile.ignitionThreshold = 0.8f; // How much heat needed to ignite
                tile.heatAccumulated = 0.0f;
                tile.burnTime = 0.0f;
                flammableCount++;
            }
            // If it's currently marked as flammable but NOT furniture, change it to floor
            else if (tile.state == TileState::Flammable)
            {
                tile.state = TileState::Floor;
            }
        }
    }

    std::cout << "  ✓ Marked " << flammableCount << " furniture tiles as flammable" << std::endl;
}

