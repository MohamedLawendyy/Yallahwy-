void Map::clearGrid()
{
    for (size_t y = 0; y < HEIGHT; ++y)
    {
        for (size_t x = 0; x < WIDTH; ++x)
        {
            grid_[y][x].state = TileState::Floor;
            grid_[y][x].wallType = WallType::None;
            grid_[y][x].hasClock = false;
            grid_[y][x].isDoor = false;
            grid_[y][x].burnTime = 0.0f;
            grid_[y][x].heatAccumulated = 0.0f;
            grid_[y][x].propVariant = 0;
        }
    }
}

void Map::clearPhysicsBodies()
{
    if (physicsWorld_)
    {
        for (b2Body *body : wallBodies_)
        {
            if (body)
            {
                physicsWorld_->DestroyBody(body);
            }
        }
    }
    wallBodies_.clear();
}

void Map::initializeGrid()
{
    clearGrid();

    std::cout << "Creating default bordered map..." << std::endl;

    // Create walls around the border
    for (size_t x = 0; x < WIDTH; ++x)
    {
        grid_[0][x].state = TileState::Wall;
        grid_[HEIGHT - 1][x].state = TileState::Wall;
    }
    for (size_t y = 0; y < HEIGHT; ++y)
    {
        grid_[y][0].state = TileState::Wall;
        grid_[y][WIDTH - 1].state = TileState::Wall;
    }

    applyAutoTiling();
    findSafeSpawnPoint();

    std::random_device rd;
    std::mt19937 gen(rd());
    convertFloorToFlammable(gen);
}

void Map::findSafeSpawnPoint()
{
    // If spawn was set by Entrance tile, we're done
    if (safeSpawnPoint_.x != 0.0f || safeSpawnPoint_.y != 0.0f)
    {
        return;
    }

    // Find the first floor tile that's not near walls
    for (size_t y = 2; y < HEIGHT - 2; ++y)
    {
        for (size_t x = 2; x < WIDTH - 2; ++x)
        {
            if (grid_[y][x].state == TileState::Floor ||
                grid_[y][x].state == TileState::Flammable)
            {
                // Check if area is clear
                bool clear = true;
                for (int dy = -1; dy <= 1; ++dy)
                {
                    for (int dx = -1; dx <= 1; ++dx)
                    {
                        if (grid_[y + dy][x + dx].state == TileState::Wall)
                        {
                            clear = false;
                            break;
                        }
                    }
                    if (!clear)
                        break;
                }

                if (clear)
                {
                    // safeSpawnPoint_ = gridToWorld(x, y);
                    // return;
                    // FIXED: Use center of tile
                    safeSpawnPoint_ = sf::Vector2f(
                        (x + 0.5f) * TILE_SIZE,
                        (y + 0.5f) * TILE_SIZE);
                    std::cout << "  Fallback spawn at grid (" << x << ", " << y << ")" << std::endl;
                    std::cout << "  World position: (" << safeSpawnPoint_.x << ", " << safeSpawnPoint_.y << ")" << std::endl;
                    return;
                }
            }
        }
    }

    // // Fallback to center
    // safeSpawnPoint_ = sf::Vector2f(
    //     (WIDTH / 2) * TILE_SIZE,
    //     (HEIGHT / 2) * TILE_SIZE);
    // Fallback to center of map
    safeSpawnPoint_ = sf::Vector2f(
        (WIDTH / 2.0f + 0.5f) * TILE_SIZE,
        (HEIGHT / 2.0f + 0.5f) * TILE_SIZE);
    std::cout << "  Using map center as spawn" << std::endl;
}

void Map::applyAutoTiling()
{
    for (size_t y = 0; y < HEIGHT; ++y)
    {
        for (size_t x = 0; x < WIDTH; ++x)
        {
            if (grid_[y][x].state == TileState::Wall)
            {
                grid_[y][x].wallType = calculateWallType(x, y);
            }
        }
    }
}

WallType Map::calculateWallType(int x, int y) const
{
    bool up = isWall(x, y - 1);
    bool down = isWall(x, y + 1);
    bool left = isWall(x - 1, y);
    bool right = isWall(x + 1, y);

    // Four-way connection
    if (up && down && left && right)
        return WallType::Cross;

    // T-junctions
    if (up && down && left && !right)
        return WallType::TJunctionLeft;
    if (up && down && !left && right)
        return WallType::TJunctionRight;
    if (left && right && up && !down)
        return WallType::TJunctionTop;
    if (left && right && !up && down)
        return WallType::TJunctionBottom;

    // Corners
    if (right && down && !up && !left)
        return WallType::TopLeft;
    if (left && down && !up && !right)
        return WallType::TopRight;
    if (right && up && !down && !left)
        return WallType::BottomLeft;
    if (left && up && !down && !right)
        return WallType::BottomRight;

    // Straight walls
    if (left && right && !up && !down)
        return WallType::Horizontal;
    if (up && down && !left && !right)
        return WallType::Vertical;

    // End caps
    if (right && !left && !up && !down)
        return WallType::EndLeft;
    if (left && !right && !up && !down)
        return WallType::EndRight;
    if (down && !up && !left && !right)
        return WallType::EndTop;
    if (up && !down && !left && !right)
        return WallType::EndBottom;

    return WallType::Top;
}

bool Map::isWall(int x, int y) const
{
    if (x < 0 || x >= static_cast<int>(WIDTH) ||
        y < 0 || y >= static_cast<int>(HEIGHT))
        return false;

    return grid_[y][x].state == TileState::Wall;
}

void Map::convertFloorToFlammable(std::mt19937 &gen)
{
    std::uniform_real_distribution<float> dis(0.0f, 1.0f);

    for (size_t y = 0; y < HEIGHT; ++y)
    {
        for (size_t x = 0; x < WIDTH; ++x)
        {
            if (grid_[y][x].state == TileState::Floor)
            {
                if (dis(gen) < config_.flammableDensity)
                {
                    grid_[y][x].state = TileState::Flammable;
                    grid_[y][x].ignitionThreshold = 0.8f + dis(gen) * 0.4f;
                }
            }
        }
    }
}

void Map::createPhysicsColliders()
{
    if (!physicsWorld_)
        return;

    clearPhysicsBodies();

    std::cout << "Creating physics colliders..." << std::endl;

    for (size_t y = 0; y < HEIGHT; ++y)
    {
        for (size_t x = 0; x < WIDTH; ++x)
        {
            if (grid_[y][x].state == TileState::Wall)
            {
                createWallCollider(x, y);
            }
        }
    }
    createFurnitureColliders(physicsWorld_);
    std::cout << "✓ Created " << wallBodies_.size() << " wall colliders" << std::endl;
}

void Map::createWallCollider(int x, int y)
{
    b2BodyDef bodyDef;
    bodyDef.type = b2_staticBody;

    // Box2D position is the center of the body
    float centerX = (x + 0.5f) * TILE_SIZE;
    float centerY = (y + 0.5f) * TILE_SIZE;

    // Convert to Box2D units (30 pixels = 1 meter)
    bodyDef.position.Set(centerX / 30.0f, centerY / 30.0f);

    b2Body *body = physicsWorld_->CreateBody(&bodyDef);

    b2PolygonShape shape;
    float halfSize = (TILE_SIZE / 2.0f) / 30.0f;
    shape.SetAsBox(halfSize, halfSize);

    b2FixtureDef fixtureDef;
    fixtureDef.shape = &shape;
    fixtureDef.density = 1.0f;
    fixtureDef.friction = 0.3f;

    body->CreateFixture(&fixtureDef);

    wallBodies_.push_back(body);
}

