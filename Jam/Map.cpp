bool Map::isValidPosition(int x, int y) const
{
    return x >= 0 && x < static_cast<int>(WIDTH) &&
           y >= 0 && y < static_cast<int>(HEIGHT);
}

bool Map::isWalkable(int x, int y) const
{
    if (!isValidPosition(x, y))
        return false;
    TileState state = grid_[y][x].state;
    return state != TileState::Wall && state != TileState::Prop;
}

sf::FloatRect Map::getTileCollisionRect(int x, int y) const
{
    return sf::FloatRect(
        x * TILE_SIZE,
        y * TILE_SIZE,
        TILE_SIZE,
        TILE_SIZE);
}

bool Map::canPlaceBody(sf::FloatRect bodyRect) const
{
    int minX = static_cast<int>(bodyRect.left / TILE_SIZE);
    int maxX = static_cast<int>((bodyRect.left + bodyRect.width) / TILE_SIZE);
    int minY = static_cast<int>(bodyRect.top / TILE_SIZE);
    int maxY = static_cast<int>((bodyRect.top + bodyRect.height) / TILE_SIZE);

    for (int y = minY; y <= maxY; ++y)
    {
        for (int x = minX; x <= maxX; ++x)
        {
            if (!isWalkable(x, y))
                return false;
        }
    }
    return true;
}

std::pair<int, int> Map::worldToGrid(sf::Vector2f worldPos) const
{
    int gridX = static_cast<int>(worldPos.x / TILE_SIZE);
    int gridY = static_cast<int>(worldPos.y / TILE_SIZE);
    return {gridX, gridY};
}

sf::Vector2f Map::gridToWorld(size_t x, size_t y) const
{
    return sf::Vector2f(
        (x + 0.5f) * TILE_SIZE,
        (y + 0.5f) * TILE_SIZE);
}

sf::Vector2f Map::getSafeSpawnPoint() const
{
    return safeSpawnPoint_;
}

void Map::reset()
{
    // Reload from CSV
    if (!loadFromCSV("maps/map_1.csv"))
    {
        initializeGrid();
    }

    // Recreate physics colliders
    if (physicsWorld_)
    {
        createPhysicsColliders();
    }
}

bool Map::isSolid(int x, int y) const
{
    if (!isValidPosition(x, y))
        return true;
    return grid_[y][x].state == TileState::Wall;
}

